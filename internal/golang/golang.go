// Package golang is protop's Go backend: a checked schema becomes Go source
// that decodes the same MessagePack the C# backend's types write.
//
// It is the `go:` annotation prefix's backend, named `golang` only because
// `go` is a keyword and cannot name a package.
//
// The target is a consumer. Section 2's rule -- tables are written, views are
// read -- makes a Go service reading a C# producer's topic the first case worth
// serving, so every emitted type gets a decoder and none gets an encoder. Adding
// encoders is adding a function here, not changing the shape of the output.
//
// The wire arithmetic is the C# backend's, unchanged: a declaration is a
// MessagePack array, and a member with tag N sits at index N-1. A decoder reads
// the array by index and skips every slot it does not know, which is what makes
// `reserved` gaps, a composite key's duplicated tuple and slots a newer producer
// appended all read the same way: as nothing.
//
// Runtime support lives in github.com/nanov/prague.go: generated code imports
// its `wire` package for decimals, and tables satisfy its `Keyed` constraint
// through CacheKey.
package golang

import (
	"fmt"
	"go/format"
	"path"
	"slices"
	"strconv"
	"strings"

	"github.com/nanov/protobuf-to-messagepack-sharp/internal/check"
	"github.com/nanov/protobuf-to-messagepack-sharp/internal/syntax"
)

// Prefix is the annotation prefix this backend reads. Annotations with any
// other prefix belong to another backend and are not copied.
const Prefix = "go"

const (
	msgpackImport = "github.com/vmihailenco/msgpack/v5"
	wireImport    = "github.com/nanov/prague.go/wire"
)

// Unit is one source file's emission. A Go package is a directory rather than
// a namespace, so a .prague file becomes one .go file, and every unit of one
// Emit call belongs to the same package.
type Unit struct {
	File   *check.File
	Name   string // <base>.go
	Source string
}

// Emit renders every file want accepts as Go in package pkg, in schema order.
// The output is gofmt-formatted; a formatting failure is a backend defect and is
// returned rather than hidden.
func Emit(s *check.Schema, pkg string, want func(*check.File) bool) ([]Unit, error) {
	var units []Unit
	for _, f := range s.Files {
		if !want(f) || len(f.Decls) == 0 {
			continue
		}
		src, err := EmitFile(f, pkg)
		if err != nil {
			return nil, err
		}
		base := strings.TrimSuffix(path.Base(f.Path), path.Ext(f.Path))
		units = append(units, Unit{File: f, Name: base + ".go", Source: src})
	}
	return units, nil
}

// EmitFile renders one file as a complete, formatted Go compilation unit.
func EmitFile(f *check.File, pkg string) (string, error) {
	var body strings.Builder
	imports := map[string]bool{}
	for _, d := range f.Decls {
		body.WriteString("\n")
		if d.Kind == check.DeclEnum {
			writeEnum(&body, d)
			continue
		}
		writeType(&body, d, imports)
	}

	var b strings.Builder
	b.WriteString("// Code generated by protopc. DO NOT EDIT.\n")
	b.WriteString("// source: ")
	b.WriteString(f.Path)
	b.WriteString("\n\npackage ")
	b.WriteString(pkg)
	b.WriteString("\n")
	if len(imports) > 0 {
		paths := make([]string, 0, len(imports))
		for p := range imports {
			paths = append(paths, p)
		}
		slices.Sort(paths)
		// Standard library first, then a blank line, as goimports groups them.
		b.WriteString("\nimport (\n")
		std := true
		for _, p := range stdFirst(paths) {
			if std && strings.Contains(p, ".") {
				std = false
				b.WriteString("\n")
			}
			b.WriteString("\t" + strconv.Quote(p) + "\n")
		}
		b.WriteString(")\n")
	}
	b.WriteString(body.String())

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("golang: %s does not format: %w\n%s", f.Path, err, b.String())
	}
	return string(out), nil
}

// stdFirst orders sorted import paths with the standard library (no dot in the
// first element) ahead of module paths.
func stdFirst(paths []string) []string {
	var std, mod []string
	for _, p := range paths {
		if strings.Contains(p, ".") {
			mod = append(mod, p)
		} else {
			std = append(std, p)
		}
	}
	return append(std, mod...)
}

// writeEnum emits a named int32 and one constant per arm, prefixed with the
// type name because Go constants share the package's scope. C# serializes an
// enum as its underlying integer, which is what int32 decodes.
func writeEnum(b *strings.Builder, d *check.Decl) {
	writeDeclAnnotations(b, d.Annotations)
	fmt.Fprintf(b, "type %s int32\n\nconst (\n", d.Name)
	for _, m := range d.EnumMembers {
		fmt.Fprintf(b, "\t%s%s %s = %d\n", d.Name, Pascal(m.Name), d.Name, m.Number)
	}
	b.WriteString(")\n")
}

func writeType(b *strings.Builder, d *check.Decl, imports map[string]bool) {
	imports[msgpackImport] = true
	imports["fmt"] = true

	writeDeclAnnotations(b, d.Annotations)
	fmt.Fprintf(b, "type %s struct {\n", d.Name)
	for _, m := range d.Members {
		if m.Kind != check.MemberField || !m.HasTag() {
			continue
		}
		t := TypeName(m.Type)
		if usesWire(m.Type) {
			imports[wireImport] = true
		}
		fmt.Fprintf(b, "\t%s %s", Pascal(m.Name), t)
		if tag := fieldTag(m.Annotations); tag != "" {
			b.WriteString(" `" + tag + "`")
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")

	if d.Kind == check.DeclTable && d.Key != nil && d.Key.Kind == check.MemberCompositeKey {
		writeKeyType(b, d)
	}
	writeDecoder(b, d)
	writeCacheKey(b, d)
	for _, m := range d.Members {
		if m.Kind == check.MemberAlias {
			writeAlias(b, d, m)
		}
	}
}

// writeDecoder emits DecodeMsgpack, which msgpack calls for *T wherever a T is
// decoded -- top level, nested, behind a pointer or inside a slice -- so one
// method per type is the whole decoder. A nil array decodes as the zero value.
func writeDecoder(b *strings.Builder, d *check.Decl) {
	fmt.Fprintf(b, "\n// DecodeMsgpack reads %s from its MessagePack array, by index, skipping unknown slots.\n", d.Name)
	fmt.Fprintf(b, "func (x *%s) DecodeMsgpack(d *msgpack.Decoder) error {\n", d.Name)
	b.WriteString("\tn, err := d.DecodeArrayLen()\n\tif err != nil {\n\t\treturn err\n\t}\n")
	b.WriteString("\tfor i := 0; i < n; i++ {\n\t\tswitch i {\n")
	for _, m := range d.Members {
		if m.Kind != check.MemberField || !m.HasTag() {
			continue
		}
		fmt.Fprintf(b, "\t\tcase %d:\n\t\t\terr = d.Decode(&x.%s)\n", m.Tag-1, Pascal(m.Name))
	}
	b.WriteString("\t\tdefault:\n\t\t\terr = d.Skip()\n\t\t}\n")
	fmt.Fprintf(b, "\t\tif err != nil {\n\t\t\treturn fmt.Errorf(\"%s[%%d]: %%w\", i, err)\n\t\t}\n", d.Name)
	b.WriteString("\t}\n\treturn nil\n}\n")
}

// writeKeyType emits a table's composite identity as a comparable struct, the
// Go spelling of the C# ValueTuple. It decodes the Kafka message key, which the
// C# side serializes as the tuple: an array of the parts in order.
func writeKeyType(b *strings.Builder, d *check.Decl) {
	name := keyTypeName(d)
	fmt.Fprintf(b, "\n// %s is %s's composite identity, and the Kafka message key of its topic.\n", name, d.Name)
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, p := range d.Key.Parts {
		fmt.Fprintf(b, "\t%s %s\n", Pascal(p.Name), TypeName(fieldFor(d, p).Type))
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "\nfunc (k *%s) DecodeMsgpack(d *msgpack.Decoder) error {\n", name)
	b.WriteString("\tn, err := d.DecodeArrayLen()\n\tif err != nil {\n\t\treturn err\n\t}\n")
	b.WriteString("\tfor i := 0; i < n; i++ {\n\t\tswitch i {\n")
	for i, p := range d.Key.Parts {
		fmt.Fprintf(b, "\t\tcase %d:\n\t\t\terr = d.Decode(&k.%s)\n", i, Pascal(p.Name))
	}
	b.WriteString("\t\tdefault:\n\t\t\terr = d.Skip()\n\t\t}\n")
	fmt.Fprintf(b, "\t\tif err != nil {\n\t\t\treturn fmt.Errorf(\"%s[%%d]: %%w\", i, err)\n\t\t}\n", name)
	b.WriteString("\t}\n\treturn nil\n}\n")
}

// writeCacheKey emits CacheKey when the declaration has identity. A composite
// key is not decoded from its own slot -- that slot duplicates the parts -- but
// built from the parts, so the value and the message key agree by construction.
func writeCacheKey(b *strings.Builder, d *check.Decl) {
	k := d.Key
	if k == nil {
		return
	}
	if k.Kind == check.MemberCompositeKey {
		root := rootTable(d)
		if root == nil || root.Key == nil {
			return
		}
		name := keyTypeName(root)
		fmt.Fprintf(b, "\n// CacheKey is %s's identity.\nfunc (x *%s) CacheKey() %s {\n\treturn %s{", d.Name, d.Name, name, name)
		for i, p := range k.Parts {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "%s: x.%s", Pascal(root.Key.Parts[i].Name), Pascal(fieldFor(d, p).Name))
		}
		b.WriteString("}\n}\n")
		return
	}
	f := fieldFor(d, k)
	fmt.Fprintf(b, "\n// CacheKey is %s's identity.\nfunc (x *%s) CacheKey() %s { return x.%s }\n",
		d.Name, d.Name, TypeName(f.Type), Pascal(f.Name))
}

// writeAlias emits an alias as a getter: it has no wire slot, and a consumer
// has nothing to set.
func writeAlias(b *strings.Builder, d *check.Decl, m *check.Member) {
	f := fieldFor(d, m)
	if f == m {
		return // #66: an alias whose target the declaration does not hold.
	}
	fmt.Fprintf(b, "\n// %s is an alias of %s.\nfunc (x *%s) %s() %s { return x.%s }\n",
		Pascal(m.Name), Pascal(f.Name), d.Name, Pascal(m.Name), TypeName(f.Type), Pascal(f.Name))
}

// fieldFor is the field of d that m reads: m itself for a field d holds, the
// aliased field for an alias, and for a member of a view's source -- a
// composite key's part -- the view member that selects it.
func fieldFor(d *check.Decl, m *check.Member) *check.Member {
	t := m
	if t.Kind == check.MemberAlias && t.Aliased != nil {
		t = t.Aliased
	}
	for _, c := range d.Members {
		if c.Kind != check.MemberField {
			continue
		}
		if c == t || c.From == t {
			return c
		}
	}
	return t
}

// rootTable is the table a declaration's identity comes from: itself, or the
// source a view chain ends at. Section 4 gives a view its source's identity,
// so a view's composite key is the table's key type, not a type of its own.
func rootTable(d *check.Decl) *check.Decl {
	for d != nil && d.Kind == check.DeclView {
		d = d.Of
	}
	if d == nil || d.Kind != check.DeclTable {
		return nil
	}
	return d
}

func keyTypeName(table *check.Decl) string { return table.Name + "Key" }

// TypeName is a resolved protop type as Go spells it. Presence becomes a
// pointer on scalars and declared types; a list is a slice either way, since a
// nil slice already means absent.
func TypeName(t check.Type) string {
	var name string
	switch t.Kind {
	case check.TypeCollection:
		if len(t.Args) == 1 {
			return "[]" + TypeName(t.Args[0])
		}
		name = "any" // map: PROTOP0900, never reaches a backend.
	case check.TypeScalar:
		name = goScalars[t.Name]
		if name == "" {
			name = t.Name
		}
	default:
		name = t.Name
	}
	if t.Optional {
		return "*" + name
	}
	return name
}

var goScalars = map[string]string{
	"int64":  "int64",
	"int32":  "int32",
	"string": "string",
	"double": "float64",
	"bool":   "bool",
	// MessagePack-CSharp writes a decimal as its invariant-culture string;
	// wire.Decimal reads that (and numeric forms) into shopspring/decimal.
	"decimal": "wire.Decimal",
}

func usesWire(t check.Type) bool {
	if t.Kind == check.TypeScalar && t.Name == "decimal" {
		return true
	}
	for _, a := range t.Args {
		if usesWire(a) {
			return true
		}
	}
	return false
}

// fieldTag joins a member's `[go: ...]` annotations into one struct tag,
// verbatim and in source order, space-separated as Go's tag convention is.
func fieldTag(anns []*syntax.Annotation) string {
	var parts []string
	for _, a := range anns {
		if a.Prefix != nil && a.Prefix.Text == Prefix {
			parts = append(parts, strings.TrimSpace(a.Text))
		}
	}
	return strings.Join(parts, " ")
}

// writeDeclAnnotations copies a declaration's `[go: ...]` annotations out as
// doc-comment lines above the type, verbatim after the `// `. A Go type has no
// attribute position, and `//` inside a bracket is a protop comment, so the
// comment marker is the backend's to add -- `[go: Deprecated: use Y.]` becomes
// `// Deprecated: use Y.`.
func writeDeclAnnotations(b *strings.Builder, anns []*syntax.Annotation) {
	for _, a := range anns {
		if a.Prefix != nil && a.Prefix.Text == Prefix {
			b.WriteString("// ")
			b.WriteString(strings.TrimSpace(a.Text))
			b.WriteString("\n")
		}
	}
}

// Pascal is the C# backend's member spelling, kept identical so that one
// schema names a member the same way in both languages: split on `_`,
// title-case each part.
func Pascal(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(strings.ToLower(part[1:]))
	}
	return b.String()
}
