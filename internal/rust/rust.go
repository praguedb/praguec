// Package rust is protop's Rust backend: a checked schema becomes Rust source
// that decodes the same MessagePack the C# backend's types write.
//
// Like the Go backend it targets a consumer, so every emitted type gets a
// decoder and none an encoder. The wire arithmetic is the C# backend's: a
// declaration is a MessagePack array, and a member with tag N sits at index
// N-1. A decoder reads the array by index and skips every slot it does not
// know, so `reserved` gaps, a composite key's duplicated tuple and slots a
// newer producer appended all read as nothing.
//
// Runtime support lives in the `prague` crate (prague.rs): generated code
// implements its `wire::Decode` and `Keyed` traits and uses its wire types.
//
// The shapes, in Rust:
//   - an enum is a newtype over i32 with one associated constant per arm, so a
//     value the schema does not know (a newer producer's arm, a flags
//     combination) is kept rather than rejected;
//   - a struct, record, table or view is a struct with a field per tagged
//     member; presence is Option, a list is Vec;
//   - a union is a Rust enum with one variant per arm and a fallback that
//     keeps an unknown arm's payload as written;
//   - a table's composite identity is a `<Table>Key` struct, which is also
//     what the Kafka message key decodes into.
package rust

import (
	"fmt"
	"path"
	"strings"

	"github.com/praguedb/praguec/internal/check"
	"github.com/praguedb/praguec/internal/syntax"
)

// Prefix is the annotation prefix this backend reads: `[rust: derive(Foo)]`
// becomes the attribute `#[derive(Foo)]` on the declaration or field.
const Prefix = "rust"

// Unit is one source file's emission: a .prague file becomes one Rust module
// file, named after it. Files of one Emit call are sibling modules, and a file
// reaches what it imports through `super::<module>`.
type Unit struct {
	File   *check.File
	Name   string // <module>.rs
	Source string
}

// Emit renders every file want accepts, in schema order.
func Emit(s *check.Schema, want func(*check.File) bool) ([]Unit, error) {
	e := &emitter{hashable: map[*check.Decl]bool{}, visiting: map[*check.Decl]bool{}}
	var units []Unit
	for _, f := range s.Files {
		if !want(f) || len(f.Decls) == 0 {
			continue
		}
		units = append(units, Unit{File: f, Name: ModuleName(f.Path) + ".rs", Source: e.file(f)})
	}
	return units, nil
}

// ModuleName is the Rust module a .prague file becomes: its base name, with
// every character a Rust identifier cannot hold as `_`.
func ModuleName(p string) string {
	base := strings.TrimSuffix(path.Base(p), path.Ext(p))
	var b strings.Builder
	for i, r := range base {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r == '_', r >= '0' && r <= '9' && i > 0:
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return strings.ToLower(b.String())
}

type emitter struct {
	hashable map[*check.Decl]bool
	visiting map[*check.Decl]bool
}

func (e *emitter) file(f *check.File) string {
	var b strings.Builder
	b.WriteString("// Code generated by praguec. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// source: %s\n\n", f.Path)
	b.WriteString("#![allow(clippy::all, dead_code, unreachable_patterns, unused_imports, non_camel_case_types)]\n\n")
	b.WriteString("use prague::wire::{self, Decode, Reader};\n")
	b.WriteString("use prague::Keyed;\n")
	for _, imp := range f.Imports {
		if len(imp.Decls) > 0 {
			fmt.Fprintf(&b, "use super::%s::*;\n", ModuleName(imp.Path))
		}
	}
	for _, d := range f.Decls {
		b.WriteString("\n")
		switch d.Kind {
		case check.DeclEnum:
			e.writeEnum(&b, d)
		case check.DeclUnion:
			e.writeUnion(&b, d)
		default:
			e.writeType(&b, d)
		}
	}
	return b.String()
}

// ---- enums ------------------------------------------------------------------

func (e *emitter) writeEnum(b *strings.Builder, d *check.Decl) {
	n := d.Name
	writeAttrs(b, "", d.Annotations)
	b.WriteString("#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]\n")
	fmt.Fprintf(b, "pub struct %s(pub i32);\n\n", n)
	fmt.Fprintf(b, "impl %s {\n", n)
	for _, m := range d.EnumMembers {
		fmt.Fprintf(b, "    pub const %s: %s = %s(%d);\n", m.Name, n, n, int32(m.Number))
	}
	b.WriteString("\n    /// The arm's name, or None for a value this schema does not know.\n")
	b.WriteString("    pub fn name(self) -> Option<&'static str> {\n        match self {\n")
	for _, m := range d.EnumMembers {
		fmt.Fprintf(b, "            Self::%s => Some(%q),\n", m.Name, m.Name)
	}
	b.WriteString("            _ => None,\n        }\n    }\n}\n\n")

	fmt.Fprintf(b, "impl std::fmt::Debug for %s {\n", n)
	b.WriteString("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n")
	b.WriteString("        match self.name() {\n")
	fmt.Fprintf(b, "            Some(name) => write!(f, \"%s::{name}\"),\n", n)
	fmt.Fprintf(b, "            None => write!(f, \"%s({})\", self.0),\n", n)
	b.WriteString("        }\n    }\n}\n\n")

	// Flags enums combine arms; BitOr on every enum costs nothing.
	fmt.Fprintf(b, "impl std::ops::BitOr for %s {\n    type Output = Self;\n", n)
	fmt.Fprintf(b, "    fn bitor(self, o: Self) -> Self {\n        %s(self.0 | o.0)\n    }\n}\n\n", n)

	fmt.Fprintf(b, "impl Decode for %s {\n", n)
	b.WriteString("    fn decode(r: &mut Reader<'_>) -> Result<Self, wire::Error> {\n")
	fmt.Fprintf(b, "        i32::decode(r).map(%s)\n    }\n}\n\n", n)

	fmt.Fprintf(b, "impl wire::HeaderValue for %s {\n", n)
	b.WriteString("    fn from_header(b: &[u8]) -> Result<Self, wire::Error> {\n")
	fmt.Fprintf(b, "        <i32 as wire::HeaderValue>::from_header(b).map(%s)\n    }\n}\n", n)
}

// ---- unions -----------------------------------------------------------------

func (e *emitter) writeUnion(b *strings.Builder, d *check.Decl) {
	n, disc := d.Name, d.Discriminant.Name
	fallback := "Unknown"
	for _, a := range d.Arms {
		if check.Pascal(a.Name) == fallback {
			fallback = "UnknownArm"
		}
	}
	writeAttrs(b, "", d.Annotations)
	fmt.Fprintf(b, "#[derive(Debug, Clone, PartialEq%s)]\n", e.eqHash(d))
	fmt.Fprintf(b, "pub enum %s {\n", n)
	for _, a := range d.Arms {
		if a.Type == nil {
			fmt.Fprintf(b, "    %s,\n", check.Pascal(a.Name))
		} else {
			fmt.Fprintf(b, "    %s(%s),\n", check.Pascal(a.Name), TypeName(*a.Type))
		}
	}
	b.WriteString("    /// An arm this schema does not know: its kind and payload, as written.\n")
	fmt.Fprintf(b, "    %s(%s, wire::Raw),\n}\n\n", fallback, disc)

	fmt.Fprintf(b, "impl Default for %s {\n    fn default() -> Self {\n", n)
	if first := d.Arms[0]; first.Type == nil {
		fmt.Fprintf(b, "        Self::%s\n", check.Pascal(first.Name))
	} else {
		fmt.Fprintf(b, "        Self::%s(Default::default())\n", check.Pascal(first.Name))
	}
	b.WriteString("    }\n}\n\n")

	fmt.Fprintf(b, "impl Decode for %s {\n", n)
	fmt.Fprintf(b, "    /// Reads [arm, payload]; elements after the payload are skipped, for a later shape.\n")
	b.WriteString("    fn decode(r: &mut Reader<'_>) -> Result<Self, wire::Error> {\n")
	b.WriteString("        if r.try_nil()? {\n            return Ok(Self::default());\n        }\n")
	fmt.Fprintf(b, "        let (kind, n) = wire::union_begin(r, %q)?;\n", n)
	fmt.Fprintf(b, "        let v = match %s(kind) {\n", disc)
	for _, a := range d.Arms {
		if a.Type == nil {
			fmt.Fprintf(b, "            %s::%s => {\n                r.skip()?;\n                Self::%s\n            }\n", disc, a.Name, check.Pascal(a.Name))
		} else {
			fmt.Fprintf(b, "            %s::%s => Self::%s(Decode::decode(r).map_err(|e| e.at(%q, 1))?),\n", disc, a.Name, check.Pascal(a.Name), n)
		}
	}
	fmt.Fprintf(b, "            k => Self::%s(k, Decode::decode(r)?),\n", fallback)
	b.WriteString("        };\n        wire::union_end(r, n)?;\n        Ok(v)\n    }\n}\n")
}

// ---- structs, records, tables, views ----------------------------------------

// fields is what a declaration's struct holds: its tagged fields and the
// fields the Kafka message writes.
func fields(d *check.Decl) []*check.Member {
	var out []*check.Member
	for _, m := range d.Members {
		if m.Kind == check.MemberField && (m.HasTag() || m.Enriched()) {
			out = append(out, m)
		}
	}
	return out
}

func (e *emitter) writeType(b *strings.Builder, d *check.Decl) {
	writeAttrs(b, "", d.Annotations)
	fmt.Fprintf(b, "#[derive(Debug, Clone, PartialEq, Default%s)]\n", e.eqHash(d))
	fmt.Fprintf(b, "pub struct %s {\n", d.Name)
	for _, m := range fields(d) {
		writeAttrs(b, "    ", m.Annotations)
		fmt.Fprintf(b, "    pub %s: %s,\n", Ident(m.Name), TypeName(m.Type))
	}
	b.WriteString("}\n")

	if d.Kind == check.DeclTable && d.Key != nil && d.Key.Kind == check.MemberCompositeKey {
		e.writeKeyType(b, d)
	}
	e.writeDecoder(b, d)
	writeCacheKey(b, d)
	var aliases []*check.Member
	for _, m := range d.Members {
		if m.Kind == check.MemberAlias && fieldFor(d, m) != m {
			aliases = append(aliases, m)
		}
	}
	if len(aliases) > 0 {
		fmt.Fprintf(b, "\nimpl %s {\n", d.Name)
		for _, m := range aliases {
			f := fieldFor(d, m)
			fmt.Fprintf(b, "    /// An alias of `%s`.\n", Ident(f.Name))
			fmt.Fprintf(b, "    pub fn %s(&self) -> &%s {\n        &self.%s\n    }\n", Ident(m.Name), TypeName(f.Type), Ident(f.Name))
		}
		b.WriteString("}\n")
	}
}

// writeDecoder emits Decode: the array read by index, unknown slots skipped,
// and nil read as the default value. A type with members the Kafka message
// writes also gets enrich and its ENRICHMENT.
func (e *emitter) writeDecoder(b *strings.Builder, d *check.Decl) {
	fmt.Fprintf(b, "\nimpl Decode for %s {\n", d.Name)
	writeEnrichment(b, d)
	b.WriteString("    fn decode(r: &mut Reader<'_>) -> Result<Self, wire::Error> {\n")
	b.WriteString("        let mut x = Self::default();\n")
	b.WriteString("        if r.try_nil()? {\n            return Ok(x);\n        }\n")
	b.WriteString("        let n = r.read_array_len()?;\n")
	b.WriteString("        for i in 0..n {\n            match i {\n")
	for _, m := range d.Members {
		if m.Kind != check.MemberField || !m.HasTag() {
			continue
		}
		fmt.Fprintf(b, "                %d => x.%s = Decode::decode(r).map_err(|e| e.at(%q, i))?,\n", m.Tag-1, Ident(m.Name), d.Name)
	}
	fmt.Fprintf(b, "                _ => r.skip().map_err(|e| e.at(%q, i))?,\n", d.Name)
	b.WriteString("            }\n        }\n        Ok(x)\n    }\n")
	writeEnrich(b, d)
	b.WriteString("}\n")
}

func writeEnrichment(b *strings.Builder, d *check.Decl) {
	var headers []string
	stamped := false
	for _, m := range d.Members {
		if m.Header != nil {
			headers = append(headers, fmt.Sprintf("%q", m.Header.Name))
		}
		stamped = stamped || m.FromTimestamp
	}
	if len(headers) == 0 && !stamped {
		return
	}
	fmt.Fprintf(b, "    const ENRICHMENT: wire::Enrichment = wire::Enrichment { headers: &[%s], timestamp: %t };\n\n",
		strings.Join(headers, ", "), stamped)
}

func writeEnrich(b *strings.Builder, d *check.Decl) {
	var lines []string
	for _, m := range d.Members {
		f := Ident(m.Name)
		switch {
		case m.FromTimestamp:
			lines = append(lines, fmt.Sprintf("        self.%s = m.timestamp();", f))
		case m.Header != nil && m.Type.Optional:
			lines = append(lines, fmt.Sprintf("        wire::header_opt(m, %q, &mut self.%s);", m.Header.Name, f))
		case m.Header != nil:
			lines = append(lines, fmt.Sprintf("        wire::header(m, %q, &mut self.%s);", m.Header.Name, f))
		}
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString("\n    /// Writes the members Prague writes from the Kafka message.\n")
	b.WriteString("    fn enrich(&mut self, m: &dyn wire::Meta) {\n")
	b.WriteString(strings.Join(lines, "\n"))
	b.WriteString("\n    }\n")
}

// writeKeyType emits a table's composite identity as a hashable struct, the
// Rust spelling of the C# ValueTuple. It decodes the Kafka message key, which
// the C# side serializes as the tuple: an array of the parts in order.
func (e *emitter) writeKeyType(b *strings.Builder, d *check.Decl) {
	name := keyTypeName(d)
	fmt.Fprintf(b, "\n/// %s's composite identity, and the Kafka message key of its topic.\n", d.Name)
	b.WriteString("#[derive(Debug, Clone, PartialEq, Eq, Hash, Default)]\n")
	fmt.Fprintf(b, "pub struct %s {\n", name)
	for _, p := range d.Key.Parts {
		fmt.Fprintf(b, "    pub %s: %s,\n", Ident(p.Name), TypeName(fieldFor(d, p).Type))
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "\nimpl Decode for %s {\n", name)
	b.WriteString("    fn decode(r: &mut Reader<'_>) -> Result<Self, wire::Error> {\n")
	b.WriteString("        let mut k = Self::default();\n")
	b.WriteString("        if r.try_nil()? {\n            return Ok(k);\n        }\n")
	b.WriteString("        let n = r.read_array_len()?;\n")
	b.WriteString("        for i in 0..n {\n            match i {\n")
	for i, p := range d.Key.Parts {
		fmt.Fprintf(b, "                %d => k.%s = Decode::decode(r).map_err(|e| e.at(%q, i))?,\n", i, Ident(p.Name), name)
	}
	fmt.Fprintf(b, "                _ => r.skip().map_err(|e| e.at(%q, i))?,\n", name)
	b.WriteString("            }\n        }\n        Ok(k)\n    }\n}\n")
}

// writeCacheKey emits Keyed when the declaration has identity. A composite key
// is built from the parts, not decoded from its own slot (which duplicates
// them), so the value and the message key agree by construction.
func writeCacheKey(b *strings.Builder, d *check.Decl) {
	k := d.Key
	if k == nil {
		return
	}
	if k.Kind == check.MemberCompositeKey {
		root := rootTable(d)
		if root == nil || root.Key == nil {
			return
		}
		name := keyTypeName(root)
		fmt.Fprintf(b, "\nimpl Keyed for %s {\n    type Key = %s;\n", d.Name, name)
		fmt.Fprintf(b, "    fn cache_key(&self) -> %s {\n        %s {\n", name, name)
		for i, p := range k.Parts {
			fmt.Fprintf(b, "            %s: self.%s.clone(),\n", Ident(root.Key.Parts[i].Name), Ident(fieldFor(d, p).Name))
		}
		b.WriteString("        }\n    }\n}\n")
		return
	}
	f := fieldFor(d, k)
	t := TypeName(f.Type)
	fmt.Fprintf(b, "\nimpl Keyed for %s {\n    type Key = %s;\n", d.Name, t)
	fmt.Fprintf(b, "    fn cache_key(&self) -> %s {\n        self.%s.clone()\n    }\n}\n", t, Ident(f.Name))
}

// fieldFor is the field of d that m reads: m itself for a field d holds, the
// aliased field for an alias, and for a member of a view's source the view
// member that selects it.
func fieldFor(d *check.Decl, m *check.Member) *check.Member {
	t := m
	if t.Kind == check.MemberAlias && t.Aliased != nil {
		t = t.Aliased
	}
	for _, c := range d.Members {
		if c.Kind == check.MemberField && (c == t || c.From == t) {
			return c
		}
	}
	return t
}

// rootTable is the table a declaration's identity comes from: itself, or the
// source a view chain ends at.
func rootTable(d *check.Decl) *check.Decl {
	for d != nil && d.Kind == check.DeclView {
		d = d.Of
	}
	if d == nil || d.Kind != check.DeclTable {
		return nil
	}
	return d
}

func keyTypeName(table *check.Decl) string { return table.Name + "Key" }

// ---- Eq and Hash --------------------------------------------------------------

// eqHash is the extra derives of a declaration whose every member can be
// compared exactly and hashed, which is what lets it key a cache. A double
// cannot, so a type holding one, however deep, derives PartialEq alone.
func (e *emitter) eqHash(d *check.Decl) string {
	if e.declHashable(d) {
		return ", Eq, Hash"
	}
	return ""
}

func (e *emitter) declHashable(d *check.Decl) bool {
	if h, ok := e.hashable[d]; ok {
		return h
	}
	if e.visiting[d] {
		return true // a cycle decides nothing; the other members do
	}
	e.visiting[d] = true
	h := true
	switch d.Kind {
	case check.DeclEnum:
	case check.DeclUnion:
		for _, a := range d.Arms {
			if a.Type != nil && !e.typeHashable(*a.Type) {
				h = false
			}
		}
	default:
		for _, m := range fields(d) {
			if !e.typeHashable(m.Type) {
				h = false
			}
		}
	}
	delete(e.visiting, d)
	e.hashable[d] = h
	return h
}

func (e *emitter) typeHashable(t check.Type) bool {
	switch t.Kind {
	case check.TypeScalar:
		return t.Name != "double"
	case check.TypeCollection:
		for _, a := range t.Args {
			if !e.typeHashable(a) {
				return false
			}
		}
		return true
	default:
		return t.Decl == nil || e.declHashable(t.Decl)
	}
}

// ---- names and types ------------------------------------------------------------

// TypeName is a resolved protop type as Rust spells it. Presence is Option; a
// list is a Vec.
func TypeName(t check.Type) string {
	var name string
	switch t.Kind {
	case check.TypeCollection:
		if len(t.Args) == 1 {
			name = "Vec<" + TypeName(t.Args[0]) + ">"
		} else {
			name = "()" // map: PROTOP0900, never reaches a backend.
		}
	case check.TypeScalar:
		name = rustScalars[t.Name]
		if name == "" {
			name = t.Name
		}
	default:
		name = t.Name
	}
	if t.Optional {
		return "Option<" + name + ">"
	}
	return name
}

var rustScalars = map[string]string{
	"int64":  "i64",
	"int32":  "i32",
	"string": "String",
	"double": "f64",
	"bool":   "bool",
	"uuid":   "wire::Uuid",
	"bytes":  "wire::Bytes",
	"raw":    "wire::Raw",
	// MessagePack-CSharp writes a decimal as its invariant-culture string;
	// wire::Decimal (rust_decimal) reads that and numeric forms.
	"decimal":   "wire::Decimal",
	"timestamp": "wire::Timestamp",
	"date":      "wire::Date",
}

// Ident is a protop member name as a Rust identifier: a keyword becomes a raw
// identifier, and the four a raw identifier cannot be take a trailing `_`.
func Ident(name string) string {
	switch name {
	case "self", "Self", "super", "crate":
		return name + "_"
	}
	if rustKeywords[name] {
		return "r#" + name
	}
	return name
}

var rustKeywords = map[string]bool{
	"as": true, "async": true, "await": true, "break": true, "const": true, "continue": true,
	"dyn": true, "else": true, "enum": true, "extern": true, "false": true, "fn": true, "for": true,
	"gen": true, "if": true, "impl": true, "in": true, "let": true, "loop": true, "match": true,
	"mod": true, "move": true, "mut": true, "pub": true, "ref": true, "return": true, "static": true,
	"struct": true, "trait": true, "true": true, "type": true, "unsafe": true, "use": true,
	"where": true, "while": true, "abstract": true, "become": true, "box": true, "do": true,
	"final": true, "macro": true, "override": true, "priv": true, "try": true, "typeof": true,
	"unsized": true, "virtual": true, "yield": true,
}

// writeAttrs copies `[rust: ...]` annotations out as attributes, verbatim
// inside `#[...]`: `[rust: derive(serde::Serialize)]` becomes
// `#[derive(serde::Serialize)]`.
func writeAttrs(b *strings.Builder, indent string, anns []*syntax.Annotation) {
	for _, a := range anns {
		if a.Prefix != nil && a.Prefix.Text == Prefix {
			fmt.Fprintf(b, "%s#[%s]\n", indent, strings.TrimSpace(a.Text))
		}
	}
}
