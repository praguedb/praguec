// examplesDir is the six-file protop program the rest of the suite measures
// against. It is the driver's corpus too: it has imports, a cycle-free graph
// three deep, and declarations that emit -- so a CLI test over it is a test
// against real input rather than against a fixture written to pass.
const examplesDir = "../../examples/prague"

// researchDoc is the record the exclusion rules below were lifted from.
const researchDoc = "../../docs/research/b2tech-feed-cache.md"

// ---------------------------------------------------------------------------
// The trip-wire.
//
// B2Tech.Feed.Cache's generator rejects a candidate file before any semantic
// analysis, with no error and no diagnostic. The failure mode is a missing
// partial half and a wall of CS0246 pointing at everything except the cause.
//
// These three constants are the rule, transcribed from the research doc's
// §8.1. They are held against that doc verbatim by
// TestTheExclusionRulesAreTheOnesTheResearchRecorded, which is this test's
// anchor: there is no golden here and no -update path to regenerate, and the
// rule cannot drift without the transcription failing against the record.

// excludedSegments are the directory names the generator refuses to look
// inside. Compared case-insensitively -- see the note on caseInsensitive below.
var excludedSegments = []string{"obj", "bin", "generated"}

// excludedSuffixes are the file-name endings the generator refuses.
var excludedSuffixes = []string{".g.cs", ".generated.cs"}

// excludedBanner is the substring the generator refuses to find near the top of
// a file -- which is exactly the conventional `// <auto-generated/>` header.
const excludedBanner = "auto-generated"

// bannerWindow is how far in the generator looks for it.
//
// The record is ambiguous: b2tech-feed-cache.md:352 says the first 500
// *characters*; the same document at :432 and #25 both say the first 500
// *bytes*. The reading taken here is bytes, and it is the *looser* of the two,
// which is the opposite of what this comment used to claim.
//
// Which way strict runs turns on the direction of the assertion. The predicate
// makes the downstream generator *skip* the file, so what protopc asserts is
// that the banner is absent -- and an absence over a wider window is the harder
// thing to prove. 500 characters spans up to four times the content of 500
// bytes in UTF-8, so characters is the wider window and characters is the
// stricter test. Bytes can pass while the generator, counting characters,
// reaches further in and finds the banner.
//
// Nothing is wrong today: the two windows coincide for ASCII, and ASCII is what
// the C# backend emits. The constant is left at bytes because it is what the
// two later sources of the record say and because moving it is a change to
// which reading protopc holds itself to. If protopc's output ever carries
// non-ASCII in its first lines, this has to become a character count -- the
// comparison below slices a byte prefix, so it would become a rune slice too.
const bannerWindow = 500

// caseInsensitive says how the path comparisons above are made, and is the
// other stricter reading taken deliberately.
//
// The generator's own comparison is C#'s ordinal Contains, which is
// case-sensitive; MSBuild's DefaultItemExcludes glob is not. Neither the
// research nor #25 records which of them decides, and on macOS -- where the
// filesystem itself is case-insensitive, so a directory the user created as
// `Obj` and a build that wrote `obj` are one directory -- the difference is
// reachable. Matching case-insensitively flags more than the generator would
// skip, never less, so it is the reading that cannot produce a silent miss.
const caseInsensitive = true

// TestEmittedFilesAreVisibleToTheDownstreamGenerator is the three assertions,
// over every file a real `protopc generate` wrote.
//
// It is cheap and it is the thing that makes the trap impossible to walk back
// into. Every ecosystem default here is a trip-wire: obj/ is the conventional
// directory, .g.cs the conventional suffix, and `// <auto-generated/>` the
// conventional header a code generator writes without thinking about it. All
// three are excluded, and nothing tells you.
//
// The paths are checked relative to -o. The directory the user points -o at is
// the user's, and whether protopc should refuse to write into one named obj/ is
// output-directory ownership, which is #25 and human-in-the-loop. What is being
// asserted here is every part of the path protopc itself chose.
func TestEmittedFilesAreVisibleToTheDownstreamGenerator(t *testing.T) {
	out := t.TempDir()
	args := append([]string{"generate", "-I", examplesDir, "-o", out,
		"--manifest", filepath.Join(out, "protopc.manifest.json")}, exampleFiles(t)...)
	if code := runCLI(t, args...); code != exitOK {
		t.Fatalf("generate exited %d", code)
	}

	var checked int
	err := filepath.WalkDir(out, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(out, path)
		if err != nil {
			return err
		}
		checked++

		// One: no segment of the path protopc chose is an excluded directory.
		for _, seg := range strings.Split(filepath.ToSlash(rel), "/")[:len(strings.Split(filepath.ToSlash(rel), "/"))-1] {
			for _, bad := range excludedSegments {
				if fold(seg) == bad {
					t.Errorf("%s: path runs through a %q directory, which the downstream generator skips in silence", rel, bad)
				}
			}
		}

		// Two: the name ends with neither excluded suffix.
		for _, bad := range excludedSuffixes {
			if strings.HasSuffix(fold(rel), bad) {
				t.Errorf("%s: name ends %q, which the downstream generator skips in silence", rel, bad)
			}
		}

		// Three: the banner is not in the first bannerWindow bytes.
		head, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if len(head) > bannerWindow {
			head = head[:bannerWindow]
		}
		if strings.Contains(fold(string(head)), excludedBanner) {
			t.Errorf("%s: %q appears in the first %d bytes, and the downstream generator skips the file in silence",
				rel, excludedBanner, bannerWindow)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if checked == 0 {
		t.Fatal("generate wrote nothing, so the three assertions asserted nothing")
	}
}

// fold lowercases when the comparisons are case-insensitive, and is a no-op
// otherwise. It is a function rather than an inline ToLower so that flipping
// caseInsensitive is one edit.
func fold(s string) string {
	if caseInsensitive {
		return strings.ToLower(s)
	}
	return s
}

// TestTheExclusionRulesAreTheOnesTheResearchRecorded is what holds the
// constants above to the record.
//
// It does not check that the document still says something; it *derives* the
// rule from the document and compares it to the constants, so neither side can
// move without the other. That is the lesson from M5: a rule held only by other
// copies of itself can be regenerated past. There is no golden here and no
// -update path -- the right-hand side of every assertion is three lines of a
// research document nobody regenerates, and correcting the record fails this
// test until somebody reads the correction.
func TestTheExclusionRulesAreTheOnesTheResearchRecorded(t *testing.T) {
	b, err := os.ReadFile(researchDoc)
	if err != nil {
		t.Fatal(err)
	}
	doc := string(b)

	// §8.1's rule is three lines in a fenced block. They are found by their
	// opening words rather than by line number so that an edit above them does
	// not silently stop this test from finding anything.
	segLine := findLine(t, doc, "filePath contains ")
	sufLine := findLine(t, doc, "filePath ends with ")
	banLine := findLine(t, doc, "the first ")

	// The directory rule is written as separator-wrapped fragments -- "\obj\",
	// "/obj/" -- because the generator matches a path substring. A segment is
	// what is left when the separators come off.
	var wantSegments []string
	for _, tok := range quoted(segLine) {
		seg := strings.ToLower(strings.Trim(tok, `\/`))
		if seg != "" && !slices.Contains(wantSegments, seg) {
			wantSegments = append(wantSegments, seg)
		}
	}
	if !slices.Equal(excludedSegments, wantSegments) {
		t.Errorf("excludedSegments = %v, but the research records %v\n  %s", excludedSegments, wantSegments, segLine)
	}

	if wantSuffixes := quoted(sufLine); !slices.Equal(excludedSuffixes, wantSuffixes) {
		t.Errorf("excludedSuffixes = %v, but the research records %v\n  %s", excludedSuffixes, wantSuffixes, sufLine)
	}

	if want := quoted(banLine); len(want) != 1 || want[0] != excludedBanner {
		t.Errorf("excludedBanner = %q, but the research records %v\n  %s", excludedBanner, want, banLine)
	}
	if want := number(t, banLine); want != bannerWindow {
		t.Errorf("bannerWindow = %d, but the research records %d\n  %s", bannerWindow, want, banLine)
	}

	// And the ambiguity this file resolves. :352 above says characters; this
	// line says bytes, and bytes is the reading taken. A correction to either
	// has to come through here.
	if !strings.Contains(doc, "in the first 500 bytes are hard requirements") {
		t.Error("the research no longer says 500 bytes at §11.H; the window in this file was chosen against that line")
	}
	if !strings.Contains(banLine, "characters") {
		t.Errorf("§8.1 no longer says characters, so the ambiguity noted on bannerWindow may be gone:\n  %s", banLine)
	}
}

// findLine returns the one line of doc beginning with prefix, and fails if
// there is not exactly one. Exactly one, because two would mean the rule was
// restated somewhere and this test would be reading whichever came first.
func findLine(t *testing.T, doc, prefix string) string {
	t.Helper()
	var found []string
	for _, line := range strings.Split(doc, "\n") {
		if strings.HasPrefix(line, prefix) {
			found = append(found, line)
		}
	}
	if len(found) != 1 {
		t.Fatalf("%d lines of the research begin %q, want exactly 1", len(found), prefix)
	}
	return found[0]
}

var quotedRE = regexp.MustCompile(`"([^"]*)"`)

// quoted is every double-quoted token of a line, in order.
func quoted(line string) []string {
	var out []string
	for _, m := range quotedRE.FindAllStringSubmatch(line, -1) {
		out = append(out, m[1])
	}
	return out
}

var numberRE = regexp.MustCompile(`\b(\d+)\b`)

// number is the one integer on a line.
func number(t *testing.T, line string) int {
	t.Helper()
	m := numberRE.FindAllString(line, -1)
	if len(m) != 1 {
		t.Fatalf("%d numbers on %q, want exactly 1", len(m), line)
	}
	n, err := strconv.Atoi(m[0])
	if err != nil {
		t.Fatal(err)
	}
	return n
}

