// What each command does and does not do.

// `check` is `generate` without the writing. Asserted by running it in an empty
// directory and finding the directory still empty -- not by reading the source
// and believing it.
func TestCheckWritesNothing(t *testing.T) {
	examples := absExamples(t)
	dir := t.TempDir()
	t.Chdir(dir)

	if got := runCLI(t, "check", "-I", examples, filepath.Join(examples, "prague-models.protop")); got != exitOK {
		t.Fatalf("check exited %d", got)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 0 {
		t.Errorf("check wrote %d entries into the working directory", len(entries))
	}
}

// `check` does not take -o or --manifest. Accepting a flag and then ignoring it
// is worse than rejecting it: the user who writes `protopc check -o out`
// believes something was written there.
func TestCheckRejectsTheWritingFlags(t *testing.T) {
	good := filepath.Join(examplesDir, "branded.protop")
	for _, args := range [][]string{
		{"check", "-o", "out", good},
		{"check", "--manifest", "m.json", good},
	} {
		if got := runCLI(t, args...); got != exitUsage {
			t.Errorf("%v exited %d, want %d", args, got, exitUsage)
		}
	}
}

// generate writes the files it was asked for and not the ones they import.
// branded.protop imports common-feed-enums.protop, whose declarations are read
// to make sense of the target and are not the target.
func TestGenerateWritesTheTargetsAndNotTheirImports(t *testing.T) {
	out := t.TempDir()
	if got := runCLI(t, "generate", "-I", examplesDir, "-o", out,
		filepath.Join(examplesDir, "branded.protop")); got != exitOK {
		t.Fatalf("generate exited %d", got)
	}

	got := names(t, out)
	// branded.protop's three declarations, and nothing from the file it
	// imports: common-feed-enums.protop's four enums are read to resolve the
	// target's types and are not written.
	want := []string{"BaseProviderObject.cs", "Odd.cs", "StaticDataRef.cs"}
	if !slices.Equal(got, want) {
		t.Errorf("wrote %v, want %v", got, want)
	}
}

// The emitted text is the backend's, unchanged: the driver names a file and
// writes bytes, and does not decorate them. A banner is #25 Q1-Q4 and is the
// one decoration that is *also* the trip-wire, so the driver adding one would
// be both an overreach and an outage.
func TestGenerateWritesTheBackendsTextUnchanged(t *testing.T) {
	out := t.TempDir()
	if got := runCLI(t, "generate", "-I", examplesDir, "-o", out,
		filepath.Join(examplesDir, "branded.protop")); got != exitOK {
		t.Fatalf("generate exited %d", got)
	}
	b, err := os.ReadFile(filepath.Join(out, "Odd.cs"))
	if err != nil {
		t.Fatal(err)
	}
	// The first line of a protopc-emitted unit is its first using, which is
	// what the backend writes first. Anything before it is a decoration the
	// driver added.
	if first, _, _ := strings.Cut(string(b), "\n"); !strings.HasPrefix(first, "using ") {
		t.Errorf("the file starts %q, want the backend's first using line", first)
	}
}

// generate creates the output directory rather than requiring it. A build step
// that fails because a directory it is about to fill does not exist yet is a
// step that fails on every fresh clone.
func TestGenerateCreatesTheOutputDirectory(t *testing.T) {
	out := filepath.Join(t.TempDir(), "a", "b")
	if got := runCLI(t, "generate", "-I", examplesDir, "-o", out,
		filepath.Join(examplesDir, "branded.protop")); got != exitOK {
		t.Fatalf("generate exited %d", got)
	}
	if len(names(t, out)) == 0 {
		t.Error("nothing was written")
	}
}

// Two declarations of one name in two namespaces would be one file under a flat
// layout. Which of the two survives is not a thing to decide quietly: the
// layout that would separate them is #25's to choose, so until it does the
// collision is an error and not a coin toss.
func TestTwoDeclarationsThatWouldShareAFileAreAnError(t *testing.T) {
	dir := t.TempDir()
	write(t, filepath.Join(dir, "a.protop"), "revision 1;\nnamespace A;\nstruct Meta {\n  int64 id = 1;\n}\n")
	write(t, filepath.Join(dir, "b.protop"), "revision 1;\nnamespace B;\nstruct Meta {\n  int64 id = 1;\n}\n")

	out := t.TempDir()
	var stderr bytes.Buffer
	code := run([]string{"generate", "-I", dir, "-o", out,
		filepath.Join(dir, "a.protop"), filepath.Join(dir, "b.protop")}, io.Discard, &stderr)
	if code != exitUsage {
		t.Fatalf("exit %d, want %d", code, exitUsage)
	}
	if !strings.Contains(stderr.String(), "Meta.cs") {
		t.Errorf("the message does not name the file both would take:\n%s", stderr.String())
	}
}

