// Exit codes. A diagnostic is not a crash and a crash is not a diagnostic.

// The three numbers, written out. The const block above main's usage text
// promises them to anyone scripting protopc, and until now nothing held that
// promise: every assertion in this file -- the want column below included --
// compares runCLI's answer against those same constants, so the oracle only
// ever asked the implementation whether it agreed with itself. Setting
// exitDiags to 0 left all seven packages green while `protopc check` printed
// PROTOP0300 and exited 0, which is a CI job that passes on every schema
// protopc rejects.
//
// So the numbers are literals here, for the reason diag's wantCodeNumbers
// gives for the codes: reading the constant would ask it whether it agrees
// with itself. The rows that follow go on reading the constants, which is what
// makes them readable -- what was missing is not there, it is here, in
// something that says what the constants ARE.
//
// The message on each says what the number means to the caller, because that
// is what a caller branches on: 1 is protopc having read the schema and having
// something to say about it, 2 is protopc never having got that far.
func TestTheExitCodesAreTheNumbersTheyAreDocumentedAs(t *testing.T) {
	for _, tc := range []struct {
		name string
		got  int
		want int
		why  string
	}{
		{"exitOK", exitOK, 0, "success is 0 or every caller of protopc reads a clean compile as a failure"},
		{"exitDiags", exitDiags, 1, "1 is what tells a build the SCHEMA is wrong; any other number and a CI job greps protopc's output for trouble, finds errors, and passes anyway"},
		{"exitUsage", exitUsage, 2, "2 is what tells a build the COMMAND is wrong -- a missing file or a flag protopc does not have -- and is what keeps that apart from a schema protopc read and rejected"},
	} {
		if tc.got != tc.want {
			t.Errorf("%s = %d, want %d: %s", tc.name, tc.got, tc.want, tc.why)
		}
	}

	// And they are three different numbers. Two that collided would make the
	// distinction the const block's comment draws -- a diagnostic is not a
	// crash -- unreadable by the only thing that reads it.
	if exitOK == exitDiags || exitOK == exitUsage || exitDiags == exitUsage {
		t.Errorf("exit codes collide: ok=%d diags=%d usage=%d", exitOK, exitDiags, exitUsage)
	}
}

func TestExitCodes(t *testing.T) {
	good := filepath.Join(examplesDir, "branded.prague")
	broken := writeTemp(t, "broken.prague", "revision 1;\nnamespace A;\nstruct S {\n  int64 id = 0;\n}\n")
	unparsable := writeTemp(t, "unparsable.prague", "revision 1;\nnamespace A;\nstruct {\n")
	missingImport := writeTemp(t, "orphan.prague", "revision 1;\nnamespace A;\nimport \"gone.prague\";\nstruct S {\n  int64 id = 1;\n}\n")

	for _, tc := range []struct {
		name string
		args []string
		want int
	}{
		{"a clean check", []string{"check", "-I", examplesDir, good}, exitOK},
		{"a schema with an error", []string{"check", broken}, exitDiags},
		{"a file that does not parse", []string{"check", unparsable}, exitDiags},
		{"an import that names no file", []string{"check", missingImport}, exitDiags},
		{"no arguments at all", nil, exitUsage},
		{"a command protopc does not have", []string{"lint", good}, exitUsage},
		{"no input files", []string{"check"}, exitUsage},
		{"an input that is not there", []string{"check", "nosuch.prague"}, exitUsage},
		{"a -I that is not there", []string{"check", "-I", "nosuch", good}, exitUsage},
		{"a format protopc does not have", []string{"check", "--error-format=json", good}, exitUsage},
		{"a flag protopc does not have", []string{"check", "--strict", good}, exitUsage},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := runCLI(t, tc.args...); got != tc.want {
				t.Errorf("exit %d, want %d", got, tc.want)
			}
		})
	}
}

// The import in bo-models.prague resolves only when -I names the directory its
// siblings are in, which is the pairing the case above leans on: the same file
// is exit 1 without the root and exit 0 with it. Without this, that case would
// pass for a reason that has nothing to do with imports.
func TestTheSameFileIsCleanOnceItsRootIsGiven(t *testing.T) {
	f := filepath.Join(examplesDir, "bo-models.prague")
	if got := runCLI(t, "check", "-I", examplesDir, f); got != exitOK {
		t.Errorf("exit %d with the root, want 0", got)
	}
	// And says nothing while doing it. A clean run that writes so much as a
	// newline to stderr is a clean run that a build log records as output, and
	// a CI job that greps stderr for trouble finds some.
	if got := stderrOf(t, "check", "-I", examplesDir, f); got != "" {
		t.Errorf("a clean check wrote to stderr: %q", got)
	}
}

// The exit code is read from the bag check.Check filled.
//
// Every other exit-1 case above is raised by the parser or by the loader, so
// without this one nothing in the suite says the checker's diagnostics reach
// the exit code at all -- and a `check` command that runs the checker and
// throws its findings away is a `check` command that passes everything. Two
// codes from two different passes of the checker, because one would pass for a
// driver that happened to keep the bag of the first pass.
func TestACheckerDiagnosticIsWhatDecidesTheExitCode(t *testing.T) {
	for _, tc := range []struct{ name, code, text string }{
		{
			"a type that resolves to nothing", "PROTOP0311",
			"revision 1;\nnamespace A;\nstruct S {\n  Nope id = 1;\n}\n",
		},
		{
			"a view selecting one member twice", "PROTOP0303",
			"revision 1;\nnamespace A;\ntable T {\n  key int64 id = 1;\n  string s = 2;\n}\nview V of T {\n  s as a;\n  s as b;\n}\n",
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := writeTemp(t, "checker.prague", tc.text)
			var stderr bytes.Buffer
			if got := run([]string{"check", f}, io.Discard, &stderr); got != exitDiags {
				t.Errorf("exit %d, want %d\n%s", got, exitDiags, stderr.String())
			}
			if !strings.Contains(stderr.String(), tc.code) {
				t.Errorf("%s was not reported:\n%s", tc.code, stderr.String())
			}
		})
	}
}

